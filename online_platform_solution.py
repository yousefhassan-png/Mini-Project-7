# الخطوة 4: تجزئة الطلاب (RFM + K-Means)
# =====================================================================
عنوان('الخطوة 4: حساب RFM لكل طالب')

# تاريخ المرجع: اليوم التالي لآخر عملية شراء في البيانات
تاريخ_المرجع = المشتريات['purchase_date'].max() + pd.Timedelta(days=1)
print('تاريخ المرجع لحساب الأيام:', تاريخ_المرجع.date())

# نجمع بيانات كل طالب:
# R = عدد الأيام من آخر شراء ، F = عدد الكورسات المشتراة ، M = إجمالي المبلغ
جدول_RFM = المشتريات.groupby('student_id').agg(
    R=('purchase_date', lambda التواريخ_الطالب: (تاريخ_المرجع - التواريخ_الطالب.max()).days),
    F=('course', 'count'),
    M=('price', 'sum')
)
print(جدول_RFM.head())
print()
print(جدول_RFM.describe().round(1))

# --- Scaling: نوحد المقاييس حتى لا يطغى عمود على عمود ---
عنوان('الخطوة 4: Scaling و Elbow Method')
المقياس = StandardScaler()
بيانات_مقيسة = المقياس.fit_transform(جدول_RFM[['R', 'F', 'M']])

# --- Elbow: نجرب k من 1 إلى 8 ونسجل قيمة inertia ---
قيم_k = range(1, 9)
قيم_inertia = []
for k in قيم_k:
    تجربة = KMeans(n_clusters=k, n_init=10, random_state=42)
    تجربة.fit(بيانات_مقيسة)
    قيم_inertia.append(تجربة.inertia_)
    if k > 1:
        درجة_silhouette = silhouette_score(بيانات_مقيسة, تجربة.labels_)
        print(f'k = {k} ، inertia = {تجربة.inertia_:.1f} ، silhouette = {درجة_silhouette:.3f}')
    else:
        print(f'k = {k} ، inertia = {تجربة.inertia_:.1f}')

plt.figure(figsize=(8, 5))
plt.plot(list(قيم_k), قيم_inertia, marker='o', color='purple')
plt.title(عربي('طريقة Elbow لاختيار عدد المجموعات k'))
plt.xlabel(عربي('عدد المجموعات k'))
plt.ylabel('inertia')
احفظ_واعرض('رسمة_4_Elbow.png')

# نختار k = 4: بعد k = 3 يصبح انخفاض inertia بطيئاً (انكسار الكوع)،
# و k = 4 يعطي مجموعات واضحة المعنى ويمكن إعطاء كل مجموعة إجراءً مختلفاً.
أفضل_k = 4
print(f'القيمة المختارة: k = {أفضل_k}')

# --- تدريب K-Means وإضافة عمود segment ---
نموذج_التجزئة = KMeans(n_clusters=أفضل_k, n_init=10, random_state=42)
جدول_RFM['رقم_المجموعة'] = نموذج_التجزئة.fit_predict(بيانات_مقيسة)

# --- نفهم كل مجموعة من متوسطات R و F و M ---
متوسطات_المجموعات = جدول_RFM.groupby('رقم_المجموعة')[['R', 'F', 'M']].mean()

# نسمي المجموعات تلقائياً حسب خصائصها:
#   الأبطال: أعلى إنفاق ، في خطر: أطول غياب ، والمجموعتان المتبقيتان نفرق بينهما بالإنفاق
رقم_الأبطال = متوسطات_المجموعات['M'].idxmax()
رقم_في_خطر = متوسطات_المجموعات['R'].idxmax()
الأرقام_المتبقية = [رقم for رقم in متوسطات_المجموعات.index if رقم not in (رقم_الأبطال, رقم_في_خطر)]
الأرقام_المتبقية = sorted(الأرقام_المتبقية, key=lambda رقم: متوسطات_المجموعات.loc[رقم, 'M'])
رقم_الجدد = الأرقام_المتبقية[0]        # إنفاق أقل
رقم_المنتظمين = الأرقام_المتبقية[1]    # إنفاق أعلى

أسماء_المجموعات = {
    رقم_الأبطال: 'الأبطال (Champions)',
    رقم_في_خطر: 'في خطر (At Risk)',
    رقم_المنتظمين: 'المنتظمون (Regular)',
    رقم_الجدد: 'الجدد/خفيفو النشاط (New)',
}
جدول_RFM['segment'] = جدول_RFM['رقم_المجموعة'].map(أسماء_المجموعات)

ملخص_المجموعات = جدول_RFM.groupby('segment').agg(
    عدد_الطلاب=('R', 'size'),
    متوسط_R=('R', 'mean'),
    متوسط_F=('F', 'mean'),
    متوسط_M=('M', 'mean'),
    إجمالي_الإيراد=('M', 'sum')
).round(1)
ملخص_المجموعات['نسبة_من_الطلاب_%'] = (ملخص_المجموعات['عدد_الطلاب'] / len(جدول_RFM) * 100).round(1)
ملخص_المجموعات['نسبة_من_الإيراد_%'] = (ملخص_المجموعات['إجمالي_الإيراد'] / جدول_RFM['M'].sum() * 100).round(1)
عنوان('الخطوة 4: ملخص المجموعات')
print(ملخص_المجموعات)

# رسمة: كل طالب كنقطة (F مقابل M) ملون حسب مجموعته
plt.figure(figsize=(9, 6))
for اسم_المجموعة in ملخص_المجموعات.index:
    بيانات_المجموعة = جدول_RFM[جدول_RFM['segment'] == اسم_المجموعة]
    plt.scatter(بيانات_المجموعة['F'] + np.random.uniform(-0.15, 0.15, len(بيانات_المجموعة)),
                بيانات_المجموعة['M'], s=60, alpha=0.7, label=عربي(اسم_المجموعة))
plt.title(عربي('مجموعات الطلاب: عدد الكورسات (F) مقابل المبلغ المصروف (M)'))
plt.xlabel(عربي('عدد الكورسات المشتراة (F)'))
plt.ylabel(عربي('إجمالي المبلغ المصروف (M)'))
plt.legend()
احفظ_واعرض('رسمة_5_مجموعات_الطلاب.png')

# رسمة: متوسط الأيام منذ آخر شراء لكل مجموعة
plt.figure(figsize=(8, 5))
sns.barplot(x=[عربي(اسم) for اسم in ملخص_المجموعات.index], y=ملخص_المجموعات['متوسط_R'].values, color='coral')
plt.title(عربي('متوسط الأيام منذ آخر شراء (R) لكل مجموعة'))
plt.xlabel(عربي('المجموعة'))
plt.ylabel(عربي('الأيام'))
احفظ_واعرض('رسمة_6_متوسط_R_لكل_مجموعة.png')

