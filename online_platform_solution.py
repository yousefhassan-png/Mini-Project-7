# الخطوة 3: التحليل التنبؤي (Linear Regression)
# =====================================================================
عنوان('الخطوة 3: Linear Regression للإيراد الشهري')

# الخطوة 1: نحول الأشهر إلى أرقام متسلسلة 1، 2، 3 ... 24
رقم_الشهر = np.arange(1, len(الإيراد_الشهري) + 1)
المدخلات = رقم_الشهر.reshape(-1, 1)      # sklearn يريد المدخلات بشكل عمود
القيم_الحقيقية = الإيراد_الشهري.values

# الخطوة 2: ندرب النموذج
نموذج_الاتجاه = LinearRegression()
نموذج_الاتجاه.fit(المدخلات, القيم_الحقيقية)

الميل = نموذج_الاتجاه.coef_[0]
التقاطع = نموذج_الاتجاه.intercept_
print(f'الميل (Slope) = {الميل:.2f} ، التقاطع (Intercept) = {التقاطع:.2f}')

# الخطوة 3: تفسير الميل بلغة البزنس
نسبة_الميل = الميل / متوسط_الإيراد_الشهري * 100
print(f'الميل = {الميل:.2f} دولار في الشهر، أي حوالي {نسبة_الميل:.2f}% من متوسط الإيراد الشهري.')
if abs(نسبة_الميل) < 2:
    تفسير_الميل = 'المنصة لا تنمو ولا تتراجع بشكل يُذكر: الإيراد شبه ثابت (الميل قريب جداً من الصفر).'
elif الميل > 0:
    تفسير_الميل = f'المنصة في نمو بمعدل تقريبي {الميل:.1f} دولار إضافي كل شهر.'
else:
    تفسير_الميل = f'المنصة في تراجع بمعدل تقريبي {abs(الميل):.1f} دولار أقل كل شهر.'
print('التفسير:', تفسير_الميل)

# الخطوة 4: R² لمعرفة هل الخط المستقيم يفسر البيانات
التوقعات_على_البيانات = نموذج_الاتجاه.predict(المدخلات)
قيمة_R2 = r2_score(القيم_الحقيقية, التوقعات_على_البيانات)
